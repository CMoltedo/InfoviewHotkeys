"""Generates Setting.Generated.cs: one key binding per built-in info view, plus
N "Other" slots (dropdown + key) for info views added by DLC or mods.

Edit the tables below and run:
    python tools/gen_settings.py

Prefab names come from the mod's log (it lists every info view each time a city
loads). English names are the game's own strings (Infoviews.INFOVIEW[<prefab>]).
Groups and order follow the in-game Info Views menu (InfoviewPrefab.m_Group / m_Priority).
"""

import os

OTHER_SLOT_COUNT = 5

# (group id, section header, [(prefab name, English label), ...])
GROUPS = [
    ("Utilities", "Roads & Utilities", [
        ("Roads", "Roads"),
        ("Traffic", "Traffic"),
        ("Electricity", "Electricity"),
        ("WaterPipes", "Water & Sewage"),
    ]),
    ("Emergency", "Health, Garbage & Emergency", [
        ("Healthcare", "Healthcare & Deathcare"),
        ("Garbage", "Garbage Management"),
        ("FireRescue", "Fire & Rescue"),
        ("DisasterControl", "Disaster Control"),
    ]),
    ("Civic", "Police, Administration & Education", [
        ("Police", "Police"),
        ("Administration", "Administration"),
        ("Education", "Education"),
    ]),
    ("Transport", "Transport & Communications", [
        ("Transport", "Transportation"),
        ("Bicycles", "Bicycles"),
        ("PostService", "Post"),
        ("TelecomService", "Telecom"),
    ]),
    ("Leisure", "Leisure & Tourism", [
        ("Leisure", "Leisure"),
        ("Tourism", "Tourism"),
        ("OutsideConnections", "Outside Connections"),
    ]),
    ("Zoning", "Zoning", [
        ("Residential", "Residential"),
        ("Commercial", "Commercial"),
        ("Industrial", "Industrial"),
        ("Office", "Office"),
    ]),
    ("Economy", "Buildings & Economy", [
        ("Level", "Building Level"),
        ("LandValue", "Land Value"),
        ("Profitability", "Company Profitability"),
        ("Extractors", "Natural Resources"),
    ]),
    ("Citizens", "Citizens", [
        ("Population", "Population"),
        ("Happiness", "Happiness"),
        ("Wealth", "Household Wealth"),
        ("Workplaces", "Workplace Availability"),
    ]),
    ("Pollution", "Pollution", [
        ("AirPollution", "Air Pollution"),
        ("GroundPollution", "Ground Pollution"),
        ("NoisePollution", "Noise Pollution"),
        ("WaterPollution", "Water Pollution"),
    ]),
]

USAGES = ("Usages.kDefaultUsage, Usages.kOverlayUsage, Usages.kToolUsage, "
          "Usages.kCancelableToolUsage, Usages.kEditorUsage")


def cs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def action_name(prefab):
    return f"Infoview_{prefab}"


def key_property(prefab):
    return f"{prefab}Key"


def other_action(i):
    return f"OtherInfoview{i:02}"


group_ids = [g[0] for g in GROUPS]
order = ", ".join(cs(g) for g in group_ids) + ", kOtherGroup, kBehaviorGroup, kMaintenanceGroup, kAboutGroup"

o = []
o.append("// <auto-generated>")
o.append("// Generated by tools/gen_settings.py. Edit the tables in that script and re-run it")
o.append("// instead of editing this file.")
o.append("// </auto-generated>")
o.append("")
o.append("namespace InfoviewHotkeys")
o.append("{")
o.append("    using Game.Input;")
o.append("    using Game.Settings;")
o.append("")
o.append(f"    [SettingsUIGroupOrder({order})]")
o.append(f"    [SettingsUIShowGroupName({order})]")
for _, _, views in GROUPS:
    for prefab, _ in views:
        o.append(f"    [SettingsUIKeyboardAction({cs(action_name(prefab))}, {USAGES})]")
for i in range(1, OTHER_SLOT_COUNT + 1):
    o.append(f"    [SettingsUIKeyboardAction({cs(other_action(i))}, {USAGES})]")
o.append("    public partial class Setting")
o.append("    {")
o.append(f"        public const int kOtherSlotCount = {OTHER_SLOT_COUNT};")
o.append("")
o.append("        /// <summary>Section headers on the Info views tab, in menu order.</summary>")
o.append("        public static readonly (string Id, string EnglishName)[] kBuiltinGroups =")
o.append("        {")
for gid, header, _ in GROUPS:
    o.append(f"            ({cs(gid)}, {cs(header)}),")
o.append("        };")
o.append("")
o.append("        /// <summary>Built-in info views that get their own binding row, in menu order.</summary>")
o.append("        public static readonly BuiltinInfoview[] kBuiltinInfoviews =")
o.append("        {")
for gid, _, views in GROUPS:
    for prefab, label in views:
        o.append(f"            new BuiltinInfoview({cs(prefab)}, {cs(action_name(prefab))}, "
                 f"nameof({key_property(prefab)}), {cs(gid)}, {cs(label)}),")
o.append("        };")
for gid, _, views in GROUPS:
    for prefab, _ in views:
        o.append("")
        o.append(f"        [SettingsUISection(kHotkeysTab, {cs(gid)})]")
        o.append(f"        [SettingsUIKeyboardBinding({cs(action_name(prefab))})]")
        o.append(f"        public ProxyBinding {key_property(prefab)} {{ get; set; }}")
for i in range(1, OTHER_SLOT_COUNT + 1):
    o.append("")
    o.append("        [SettingsUISection(kOtherTab, kOtherGroup)]")
    o.append("        [SettingsUIDropdown(typeof(Setting), nameof(GetOtherInfoviewDropdownItems))]")
    o.append("        [SettingsUIValueVersion(typeof(Setting), nameof(GetInfoviewListVersion))]")
    o.append(f"        public string Other{i:02}Infoview {{ get => GetOtherSlotInfoview({i}); set => SetOtherSlot({i}, value); }}")
    o.append("")
    o.append("        [SettingsUISection(kOtherTab, kOtherGroup)]")
    o.append(f"        [SettingsUIKeyboardBinding({cs(other_action(i))})]")
    o.append(f"        public ProxyBinding Other{i:02}Key {{ get; set; }}")
o.append("    }")
o.append("}")

target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Setting.Generated.cs")
with open(target, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(o) + "\n")
count = sum(len(v) for _, _, v in GROUPS)
print(f"Wrote {count} built-in info views and {OTHER_SLOT_COUNT} other slots to {os.path.normpath(target)}")
